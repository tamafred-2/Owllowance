import { expect, test } from '@playwright/test';

test('Manage wallet keeps rename optional and adds income to the chosen wallet', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByLabel('Opening balance (PHP)', { exact: true }).fill('100');
  await page.getByRole('button', { name: 'Create wallet', exact: true }).click();
  await page.getByRole('link', { name: 'Wallet', exact: true }).click();
  await page.getByRole('button', { name: 'Add wallet', exact: true }).click();
  await page.getByLabel('Wallet name', { exact: true }).fill('Savings');
  await page.getByRole('button', { name: 'Create wallet', exact: true }).click();
  await page.getByRole('link', { name: 'Manage Savings', exact: true }).click();
  await expect(page.getByLabel('Wallet name', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('manage-light.png'), fullPage: true });
  await page.getByRole('button', { name: 'Edit name', exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath('rename-modal.png'), fullPage: true });
  await page.getByLabel('Wallet name', { exact: true }).fill('Discard this');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByLabel('Wallet name', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Edit name', exact: true }).click();
  await expect(page.getByLabel('Wallet name', { exact: true })).toHaveValue('Savings');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: testInfo.outputPath('manage-dark.png'), fullPage: true });
  await page.getByRole('button', { name: 'Add money', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Income', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('radio', { name: 'Wallet: Savings', exact: true })).toBeChecked();
  await page.getByLabel('Amount (PHP)', { exact: true }).fill('50');
  await page.getByRole('radio', { name: 'Allowance', exact: true }).click();
  await page.getByRole('button', { name: 'Save income', exact: true }).click();
  await expect(page.getByText('Income saved.', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Manage wallet', exact: true })).toBeVisible();
  await expect(page.getByText('Savings', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Back to Wallet', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('link', { name: 'Manage Savings', exact: true })).toContainText('50.00');
  await expect(page.getByRole('link', { name: 'Manage Cash', exact: true })).toContainText('100.00');
  await page.getByRole('link', { name: 'Manage Savings', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Archive wallet', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Back to Wallet', exact: true }).click();
  await page.getByRole('button', { name: 'Wallet options: Savings', exact: true }).click();
  await page.getByRole('button', { name: 'Archive wallet', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm archive', exact: true }).click();
  await page.getByRole('link', { name: 'Manage Savings', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Add money', exact: true })).toHaveCount(0);
});


test('wallet dropdown stays beside its trigger and opens wallet-specific actions', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Create wallet', exact: true }).click();
  await page.getByRole('link', { name: 'Wallet', exact: true }).click();
  const trigger = page.getByRole('button', { name: 'Wallet options: Cash', exact: true });
  const triggerBox = await trigger.boundingBox();
  await trigger.click();
  const menu = page.getByTestId('wallet-dropdown');
  await expect(menu).toBeVisible();
  const menuBox = await menu.boundingBox();
  expect(triggerBox).not.toBeNull(); expect(menuBox).not.toBeNull();
  expect(Math.abs(menuBox!.y - (triggerBox!.y + triggerBox!.height))).toBeLessThan(12);
  expect(menuBox!.x).toBeGreaterThanOrEqual(0);
  expect(menuBox!.x + menuBox!.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: testInfo.outputPath('dropdown-light.png'), fullPage: true });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: testInfo.outputPath('dropdown-dark.png'), fullPage: true });
  await page.getByRole('button', { name: 'Close wallet menu', exact: true }).click({ position: { x: 10, y: 10 } });
  await expect(menu).toHaveCount(0);
  await trigger.click();
  await page.getByRole('button', { name: 'Edit name', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Edit wallet name', exact: true })).toBeVisible();
  await page.getByLabel('Wallet name', { exact: true }).fill('Pocket');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm rename', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Manage wallet', exact: true })).toHaveCount(0);
  const renamed = page.getByRole('button', { name: 'Wallet options: Pocket', exact: true });
  await renamed.click();
  await page.getByRole('button', { name: 'Add money', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Income', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('radio', { name: 'Wallet: Pocket', exact: true })).toBeChecked();
  await page.getByLabel('Amount (PHP)', { exact: true }).fill('25');
  await page.getByRole('radio', { name: 'Allowance', exact: true }).click();
  await page.getByRole('button', { name: 'Save income', exact: true }).click();
  await expect(page.getByText('Income saved.', { exact: true })).toBeVisible();
  await expect(renamed).toBeVisible();
  await expect(page.getByRole('link', { name: 'Manage Pocket', exact: true })).toContainText('25.00');
});

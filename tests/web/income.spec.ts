import { expect, test } from '@playwright/test';

test('income and expense tabs retain drafts and post to the selected wallet offline', async ({ page, context }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByLabel('Opening balance (PHP)', { exact: true }).fill('100');
  await page.getByRole('button', { name: 'Create wallet', exact: true }).click();
  await page.getByRole('link', { name: 'Wallet', exact: true }).click();
  await page.getByRole('link', { name: 'Add wallet', exact: true }).click();
  await page.getByRole('radio', { name: 'Bank', exact: true }).click();
  await page.getByLabel('Wallet name', { exact: true }).fill('Income bank');
  await page.getByLabel('Opening balance (PHP)', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Create wallet', exact: true }).click();
  await page.getByRole('link', { name: 'Add transaction', exact: true }).click();
  await page.getByLabel('Amount (PHP)', { exact: true }).fill('20');
  await page.getByRole('radio', { name: 'Food & drink', exact: true }).click();
  await page.getByRole('radio', { name: 'Wallet: Income bank', exact: true }).click();
  await page.getByRole('tab', { name: 'Income', exact: true }).click();
  await expect(page.getByRole('radio', { name: 'Wallet: Income bank', exact: true })).toBeChecked();
  await expect(page.getByRole('radio', { name: 'Food & drink', exact: true })).toHaveCount(0);
  await page.getByLabel('Amount (PHP)', { exact: true }).fill('250.25');
  await page.getByRole('radio', { name: 'Allowance', exact: true }).click();
  await page.getByRole('tab', { name: 'Expense', exact: true }).click();
  await expect(page.getByLabel('Amount (PHP)', { exact: true })).toHaveValue('20');
  await expect(page.getByRole('radio', { name: 'Food & drink', exact: true })).toBeChecked();
  await page.getByRole('tab', { name: 'Income', exact: true }).click();
  await expect(page.getByLabel('Amount (PHP)', { exact: true })).toHaveValue('250.25');
  await expect(page.getByRole('radio', { name: 'Allowance', exact: true })).toBeChecked();
  await page.screenshot({ path: testInfo.outputPath('income-mobile.png'), fullPage: true });
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await context.setOffline(true);
  await page.getByRole('button', { name: 'Save income', exact: true }).click();
  await expect(page.getByText('Income saved.', { exact: true })).toBeVisible();
  await expect(page.getByTestId('today-net')).toContainText('₱250.25');
  await expect(page.getByText('₱0.00', { exact: true })).toHaveCount(1);
  await page.getByRole('link', { name: 'Wallet', exact: true }).click();
  await expect(page.getByText('₱100.00', { exact: true })).toBeVisible();
  await expect(page.getByText('₱250.25', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Add transaction', exact: true }).click();
  await page.getByLabel('Amount (PHP)', { exact: true }).fill('20');
  await page.getByRole('radio', { name: 'Food & drink', exact: true }).click();
  await page.getByRole('radio', { name: 'Wallet: Income bank', exact: true }).click();
  await page.getByRole('button', { name: 'Save expense', exact: true }).click();
  await expect(page.getByTestId('today-net')).toContainText('₱230.25');
  await expect(page.getByText('₱20.00', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Wallet', exact: true }).click();
  await page.getByRole('link', { name: 'Manage Income bank', exact: true }).click();
  const walletHistory = page.getByTestId('wallet-history');
  await expect(walletHistory.getByText('Cash in / Allowance', { exact: true })).toBeVisible();
  await expect(walletHistory.getByText('Cash out / Food & drink', { exact: true })).toBeVisible();
  await expect(walletHistory.getByText('Opening balance', { exact: true })).toHaveCount(1);
  await page.screenshot({ path: testInfo.outputPath('wallet-history-light.png'), fullPage: true });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: testInfo.outputPath('wallet-history-dark.png'), fullPage: true });
  await page.getByRole('button', { name: 'Back to Wallet', exact: true }).click();
  await page.getByRole('link', { name: 'Manage Cash', exact: true }).click();
  await expect(walletHistory.getByText('Opening balance', { exact: true })).toBeVisible();
  await expect(walletHistory.getByText('Cash in / Allowance', { exact: true })).toHaveCount(0);
  await expect(walletHistory.getByText('Cash out / Food & drink', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Back to Wallet', exact: true }).click();
  await page.getByRole('link', { name: 'History', exact: true }).click();
  await page.reload();
  await expect(page.getByText('Income / Allowance', { exact: true })).toHaveCount(1);
  await expect(page.getByText('Food & drink', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('income-history-mobile.png'), fullPage: true });
});
